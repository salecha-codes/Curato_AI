"""Reproduce the 20-customer teaching dataset and serverless fallbacks."""
from pathlib import Path
import csv
import json
import random
from collections import Counter

ROOT = Path(__file__).resolve().parents[1]
COUNTS = [10, 15, 20, 13, 14, 11, 12, 16, 17, 18, 19, 21, 22, 23, 24, 25, 26, 27, 28, 29]


def main():
    rng = random.Random(42)
    products = list(csv.DictReader((ROOT/'data/products.csv').open()))
    categories = sorted({p['category'] for p in products})
    ratings, activity = [], []
    for number, total in enumerate(COUNTS, 1):
        uid = f'U{number:03d}'
        favorite = categories[(number - 1) % len(categories)]
        # Weighted sampling without replacement, with different history lengths.
        selected = sorted(products, key=lambda p: rng.random() ** (1 / (3 if p['category'] == favorite else 1)), reverse=True)[:total]
        for p in selected:
            rating = round(max(1, min(5, rng.gauss(4.3 if p['category'] == favorite else 3.1, .7))), 1)
            ratings.append({'user_id':uid, 'product_id':p['product_id'], 'rating':rating})
        seen = {p['product_id'] for p in selected}
        remaining = sorted([p for p in products if p['product_id'] not in seen], key=lambda p: (p['category'] != favorite, p['product_id']))
        available = Counter(p['category'] for p in remaining)
        saved = []
        for p in remaining:
            # Leave an unseen alternative in every seeded category.
            if available[p['category']] <= 1:
                continue
            saved.append(p); available[p['category']] -= 1
            if len(saved) == 2 + number % 3:
                break
        for i, p in enumerate(saved):
            activity.append({'user_id': uid, 'product_id':p['product_id'], 'kind':'cart' if i == 0 else 'wishlist'})
    assert {p['product_id'] for p in ratings} == {p['product_id'] for p in products}
    for name, rows in [('ratings', ratings), ('activity', activity)]:
        with (ROOT/f'data/{name}.csv').open('w', newline='') as f:
            writer = csv.DictWriter(f, fieldnames=list(rows[0]), lineterminator='\n'); writer.writeheader(); writer.writerows(rows)
    info = {'name':'Electronics discovery sample', 'source':'Bundled synthetic teaching dataset (seed 42). Not Amazon customer data.',
            'synthetic':True, 'generation_seed':42, 'customers':20, 'rating_count_range':[10,29],
            'sample_activity':'Synthetic cart and wishlist examples; editable in the app.'}
    (ROOT/'data/dataset_info.json').write_text(json.dumps(info, indent=2)+'\n')
    embedded = '# Generated by scripts/generate_sample.py; serverless data fallback.\n'
    for constant, filename in [('DEFAULT_RATINGS_CSV','ratings.csv'), ('DEFAULT_PRODUCTS_CSV','products.csv'),
                               ('DEFAULT_ACTIVITY_CSV','activity.csv'), ('DEFAULT_INFO_JSON','dataset_info.json')]:
        embedded += f'{constant} = {(ROOT/"data"/filename).read_text()!r}\n'
    (ROOT/'backend/embedded_data.py').write_text(embedded)


if __name__ == '__main__':
    main()
